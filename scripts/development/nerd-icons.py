#!/usr/bin/env python3
# Run: nix develop -c scripts/development/nerd-icons.py
#
# Copies Nerd Font glyphs into src/lib/components/icons/nerd-icons.ts as SVG
# paths, so NerdIcon.svelte draws them without the font. Names are the
# cheat sheet names (https://www.nerdfonts.com/cheat-sheet) without "nf-".
# To add an icon, add its name here and run the script again.

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = "static/fonts/JetBrainsMonoNerdFont-Regular.woff2"
OUT = "src/lib/components/icons/nerd-icons.ts"

NAMES = [
    "dev-cloudflare",
    "dev-cplusplus",
    "dev-docker",
    "dev-grafana",
    "dev-opentelemetry",
    "dev-postgresql",
    "dev-prometheus",
    "dev-python",
    "dev-react",
    "dev-rust",
    "dev-sqlite",
    "dev-svelte",
    "dev-tailwindcss",
    "dev-typescript",
    "linux-nixos",
    "md-aws",
    "md-console_line",
    "md-email",
    "md-language_go",
    "oct-moon",
    "oct-sun",
    "md-lambda",
]

# The mark fills this much of its square box, like the GitHub and Forgejo icons.
FILL = 0.83

font = TTFont(FONT)
glyphs = font.getGlyphSet()
found = set(font.getBestCmap().values())

lines = [
    "// Generated by scripts/development/nerd-icons.py. Do not edit.",
    "// Nerd Font glyphs (https://www.nerdfonts.com) as SVG paths.",
    "export const NERD_ICONS = {",
]
for name in NAMES:
    assert name in found, f"{name} is not in {FONT}"
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    # Fonts point y up and SVG points it down, so flip the glyph.
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    side = max(x1 - x0, y1 - y0) / FILL
    left = (x0 + x1 - side) / 2
    top = (-y1 - y0 - side) / 2
    box = " ".join(f"{v:g}" for v in (left, top, side, side))
    lines.append(f'  "{name}": {{ viewBox: "{box}", d: "{pen.getCommands()}" }},')
lines += ["} as const;", "", "export type NerdIconName = keyof typeof NERD_ICONS;", ""]

with open(OUT, "w") as out:
    out.write("\n".join(lines))
print(f"{OUT}: {len(NAMES)} icons")
